const PST_MAP = {
  PAWN: PAWN_PST,
  KNIGHT: KNIGHT_PST,
  BISHOP: BISHOP_PST,
  ROOK: ROOK_PST,
  QUEEN: QUEEN_PST,
  KING: KING_MG_PST
};

class PositionEvaluator {
  evaluate(board) {
    let whiteScore = 0;
    let blackScore = 0;

    for (let r = 0; r < 8; r++) {
      for (let c = 0; c < 8; c++) {
        const piece = board.getPieceAt(r, c);
        if (piece) {
          const material = piece.type.baseValue;
          const positional = this._getPositionalScore(piece, r, c);
          const pieceScore = material + positional;
          if (piece.color === PieceColor.WHITE) {
            whiteScore += pieceScore;
          } else {
            blackScore += pieceScore;
          }
        }
      }
    }

    return whiteScore - blackScore;
  }

  _getPositionalScore(piece, row, col) {
    const tableRow = piece.color === PieceColor.WHITE ? row : (7 - row);
    const pst = PST_MAP[piece.type.name];
    return pst ? pst[tableRow][col] : 0;
  }
}

module.exports = PositionEvaluator;
